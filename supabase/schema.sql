-- Reference copy of the Sona Events database (applied to Supabase as migration "sona_events_initial_schema").
-- Tables: staff (allowlist), events, orders, order_photos. Storage bucket: uploads (private, JPEG only, 3 MB limit).
-- Guests never touch the tables directly: they call get_event() and submit_order().
-- Staff access is granted by is_staff(): a signed-in, email-confirmed user whose email is in public.staff.
--
-- To add a staff member:   insert into public.staff (email) values ('name@example.com');
-- To remove one:           delete from public.staff where email = 'name@example.com';
--
-- The full definitions live in the Supabase project under Database > Migrations.
--
-- Later changes (also under Database > Migrations):
--  * submit_order is safe to retry and accepts an optional guest note (orders.note).
--  * event_upload_paths() lists an event's uploaded photos so the staff page can delete them.
--  * Sign-ups are closed: a trigger on auth.users only lets an account be created for an email in public.staff.
--    To add staff: insert the email into public.staff first, then add the user in Supabase.
--  * order_photos keeps how each photo is framed (crop_zoom, crop_x, crop_y). Guests send the whole
--    photo, and staff can re-frame it from the staff page without the guest re-sending anything.
--  * orders.paid_at / paid_amount record payment taken at the table (set from the staff page).
--  * Special events: events.kind ('market' or 'private'), events.show_prices, and an overlay picture
--    (events.overlay_path in the public "overlays" bucket, plus overlay_scale / overlay_x / overlay_y,
--    measured on the front of the magnet). Up to 100 magnets per order (events.max_magnets, order_photos.qty).
--  * Two staff devices: order_photos.claimed_at / claimed_by reserve magnets for the sheet one device is
--    printing (claim_photos / release_photos, a reservation lasts 5 minutes unless renewed). orders,
--    order_photos and events are in the supabase_realtime publication so staff pages update at once.
--  * Print sheets are saved to the private "sheets" bucket (PDF only, staff only) and opened through a
--    link that lasts 12 hours, so a phone can open them in a new tab. They are removed with the photos.
--    Table signs are made into a one-page Letter PDF the same way (sign.html drawn out of sight, then
--    saved under the event's folder, or under signs/ where they are cleared after two days).
--  * order_photos.crop_fit: the whole photo sits on the front with white filling the rest, instead of a
--    square crop. fit_zoom / fit_x / fit_y zoom and move a fitted photo and are kept apart from the
--    square crop (crop_zoom / crop_x / crop_y), so switching between the two loses neither.
--  * Online payment (Square): events.pay_online; orders.pay_status ('pending' holds an order back from
--    printing until paid; 'failed' and 'table' let it print), pay_url, pay_amount, square_order_id,
--    square_payment_id. The "square" edge function (supabase/functions/square) makes the checkout page,
--    checks payment, and receives Square's payment.updated webhook. Its secrets live in Supabase:
--    SQUARE_ACCESS_TOKEN, SQUARE_WEBHOOK_SIGNATURE_KEY (optional SQUARE_LOCATION_ID, SQUARE_ENV=sandbox).
--    Prices in that function must match config.js.
--  * Square credentials live in private.app_secrets (schema not exposed; read/written only through
--    get_app_secret / set_app_secret, which only the service role may call). The square function
--    creates its own payment.updated webhook subscription and stores the signature key there.
