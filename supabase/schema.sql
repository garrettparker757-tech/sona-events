-- Reference copy of the Sona Events database (applied to Supabase as migration "sona_events_initial_schema").
-- Tables: staff (allowlist), events, orders, order_photos. Storage bucket: uploads (private, JPEG only, 3 MB limit).
-- Guests never touch the tables directly: they call get_event() and submit_order().
-- Staff access is granted by is_staff(): a signed-in, email-confirmed user whose email is in public.staff.
--
-- To add a staff member:   insert into public.staff (email) values ('name@example.com');
-- To remove one:           delete from public.staff where email = 'name@example.com';
--
-- The full definitions live in the Supabase project under Database > Migrations.
--
-- Later changes (also under Database > Migrations):
--  * submit_order is safe to retry and accepts an optional guest note (orders.note).
--  * event_upload_paths() lists an event's uploaded photos so the staff page can delete them.
--  * Sign-ups are closed: a trigger on auth.users only lets an account be created for an email in public.staff.
--    To add staff: insert the email into public.staff first, then add the user in Supabase.
--  * order_photos keeps how each photo is framed (crop_zoom, crop_x, crop_y). Guests send the whole
--    photo, and staff can re-frame it from the staff page without the guest re-sending anything.
--  * orders.paid_at / paid_amount record payment taken at the table (set from the staff page).
--  * Special events: events.kind ('market' or 'private'), events.show_prices, and an overlay picture
--    (events.overlay_path in the public "overlays" bucket, plus overlay_scale / overlay_x / overlay_y,
--    measured on the front of the magnet). Up to 100 magnets per order (events.max_magnets, order_photos.qty).
